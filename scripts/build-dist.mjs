#!/usr/bin/env node
// Build the vendorable kit into dist/ (committed, so an app vendors nc-ui at a pinned sha with no build step):
//   dist/nc-ui.css        tokens.css + the kit sheet (kitCss) + confirm.css, readable
//   dist/nc-ui.min.css    the same, minified
//   dist/nc-ui.min.js     src/index.js bundled (ESM, minified); confirm() links ./confirm.css next to it
//   dist/confirm.css      copy of src/primitives/confirm.css (self-contained)
//   dist/tailwind-preset.js   Tailwind v3 preset: theme keys → var(--nc-ui-*) only (S2: tokens are the source)
//   dist/tailwind-theme.css   Tailwind v4 @theme inline block, the same mapping
// `--check` builds in memory and fails if a committed file differs. `--sizes` prints min+gz sizes.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import { build, transform } from "esbuild";
import { tokenAlias } from "../src/alias.js";
import { kitCss } from "../src/primitives/kit.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");
const resolved = JSON.parse(read("dist/tokens.resolved.json"));
const HEADER = "/* @netcomposer/nc-ui: generated by scripts/build-dist.mjs from tokens/tokens.json and src/. Do not edit. */\n";

/** Semantic tokens grouped into Tailwind theme keys. Values are always var(--nc-ui-*), never a literal. */
export function tailwindTheme() {
  const theme = { colors: {}, spacing: {}, fontFamily: {}, fontSize: {}, fontWeight: {}, letterSpacing: {}, lineHeight: {}, transitionDuration: {}, minHeight: {}, minWidth: {} };
  for (const [name, entry] of Object.entries(tokenAlias)) {
    if (entry.tier !== "semantic") continue;
    const ref = `var(${entry.prop})`;
    const key = `nc-${name}`;
    if (entry.kind === "color") theme.colors[key] = ref;
    else if (entry.kind === "family") theme.fontFamily[key] = ref;
    else if (entry.kind === "duration") {
      if (/^[\d.]+m?s$/.test(String(resolved.semantic[name] ?? ""))) theme.transitionDuration[key] = ref;
    } else if (entry.kind === "length") {
      if (/-size(-|$)/.test(name)) theme.fontSize[key] = ref;
      else theme.spacing[key] = ref;
    } else if (/-weight$/.test(name)) theme.fontWeight[key] = ref;
    else if (/-tracking$/.test(name)) theme.letterSpacing[key] = ref;
    else if (/-leading$/.test(name)) theme.lineHeight[key] = ref;
  }
  for (const name of ["target-min", "target-min-coarse"]) {
    theme.minHeight[`nc-${name}`] = `var(--nc-ui-${name})`;
    theme.minWidth[`nc-${name}`] = `var(--nc-ui-${name})`;
  }
  return theme;
}

function tailwindPreset(theme) {
  return `// @netcomposer/nc-ui: generated by scripts/build-dist.mjs from tokens/tokens.json and src/. Do not edit.
// Tailwind v3 preset. Tokens are the source of truth (S2): every theme value is a var(--nc-ui-*) reference, so a
// class like \`bg-nc-accent\` or \`p-nc-module-pad\` follows tokens.json. Never add a literal here.
// Load dist/tokens.css (or nc-ui.css) once, then: presets: [require("@netcomposer/nc-ui/tailwind-preset")].
const theme = ${JSON.stringify(theme, null, 2)};
export default { theme: { extend: theme } };
export { theme };
`;
}

function tailwindThemeCss(theme) {
  const ns = { colors: "color", spacing: "spacing", fontFamily: "font", fontSize: "text", fontWeight: "font-weight", letterSpacing: "tracking", lineHeight: "leading", transitionDuration: null, minHeight: null, minWidth: null };
  const lines = [];
  for (const [group, values] of Object.entries(theme)) {
    if (!ns[group]) continue;
    for (const [key, ref] of Object.entries(values)) lines.push(`  --${ns[group]}-${key}: ${ref};`);
  }
  return `${HEADER}/* Tailwind v4: @import "@netcomposer/nc-ui/tailwind-theme.css" after tailwindcss. Values are var(--nc-ui-*) only (S2). */\n@theme inline {\n${lines.join("\n")}\n}\n`;
}

export async function outputs() {
  const kit = kitCss();
  const confirm = read("src/primitives/confirm.css");
  const css = `${HEADER}${read("dist/tokens.css")}\n/* kit: kitCss() */\n${kit.trim()}\n\n/* confirm.css */\n${confirm}`;
  const minCss = (await transform(css, { loader: "css", minify: true, legalComments: "none" })).code;
  const js = await build({
    entryPoints: [join(root, "src/index.js")],
    bundle: true,
    format: "esm",
    platform: "browser",
    target: "es2020",
    minify: true,
    legalComments: "none",
    write: false,
    banner: { js: "/* @netcomposer/nc-ui (MIT) by Peter Semmelhack, https://psem.me/. Built by scripts/build-dist.mjs. */" },
  });
  const theme = tailwindTheme();
  return {
    "dist/nc-ui.css": css,
    "dist/nc-ui.min.css": minCss,
    "dist/nc-ui.min.js": js.outputFiles[0].text,
    "dist/confirm.css": confirm,
    "dist/tailwind-preset.js": tailwindPreset(theme),
    "dist/tailwind-theme.css": tailwindThemeCss(theme),
  };
}

export function sizes(files) {
  const size = (text) => ({ min: Buffer.byteLength(text), gzip: gzipSync(text, { level: 9 }).length });
  return { css: size(files["dist/nc-ui.min.css"]), js: size(files["dist/nc-ui.min.js"]) };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const files = await outputs();
  if (process.argv.includes("--check")) {
    const stale = Object.entries(files).filter(([p, text]) => {
      try {
        return read(p) !== text;
      } catch {
        return true;
      }
    });
    if (stale.length) {
      console.error(`dist is stale (run npm run build): ${stale.map(([p]) => p).join(", ")}`);
      process.exit(1);
    }
  } else for (const [p, text] of Object.entries(files)) writeFileSync(join(root, p), text);
  const s = sizes(files);
  console.log(`dist: nc-ui.min.css ${s.css.min} B (${s.css.gzip} B gzip), nc-ui.min.js ${s.js.min} B (${s.js.gzip} B gzip)`);
}
